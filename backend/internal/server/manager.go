type Manager struct {
	store      *store.Store
	installer  *Installer
	mu         sync.RWMutex
	running    map[string]*runningServer
	starting   map[string]bool
	rootCtx    context.Context
	rootCancel context.CancelFunc
	activeOps  sync.WaitGroup
	closing    bool
}

type runningServer struct {
	cmd    *exec.Cmd
	stdin  io.WriteCloser
	done   chan struct{}
	mu     sync.Mutex
	status string
}

type CreateRequest struct {
	Name            string `json:"name"`
	Software        string `json:"software"`
	Version         string `json:"version"`
	ParentDirectory string `json:"parentDirectory"`
	MemoryMB        int    `json:"memoryMb"`
	Port            int    `json:"port"`
	EULAAccepted    bool   `json:"eulaAccepted"`
}

type ServerView struct {
	store.Server
	Status string `json:"status"`
}

var safeName = regexp.MustCompile(`^[a-zA-Z0-9][a-zA-Z0-9 _.-]{1,39}$`)

func NewManager(s *store.Store) *Manager {
	rootCtx, rootCancel := context.WithCancel(context.Background())
	m := &Manager{store: s, installer: NewInstaller(), running: make(map[string]*runningServer), starting: make(map[string]bool), rootCtx: rootCtx, rootCancel: rootCancel}
	go m.scheduleLoop()
	return m
}

func (m *Manager) Create(ctx context.Context, req CreateRequest) (store.Server, error) {
	m.mu.Lock()
	if m.closing {
		m.mu.Unlock()
		return store.Server{}, fmt.Errorf("UNNAMED PTERO is shutting down")
	}
	m.activeOps.Add(1)
	m.mu.Unlock()
	defer m.activeOps.Done()
	opCtx, cancel := context.WithCancel(ctx)
	stopRoot := context.AfterFunc(m.rootCtx, cancel)
	defer func() { stopRoot(); cancel() }()
	ctx = opCtx
	name := strings.TrimSpace(req.Name)
	if !safeName.MatchString(name) {
		return store.Server{}, fmt.Errorf("server name must be 2–40 characters and contain only letters, numbers, spaces, dots, underscores or hyphens")
	}
	software := strings.ToLower(strings.TrimSpace(req.Software))
	if software != "vanilla" && software != "paper" && software != "purpur" && software != "fabric" {
		return store.Server{}, fmt.Errorf("unsupported server software")
	}
	version := strings.TrimSpace(req.Version)
	if version == "" || len(version) > 40 {
		return store.Server{}, fmt.Errorf("enter a valid Minecraft version")
	}
	if req.MemoryMB < 1024 || req.MemoryMB > 65536 {
		return store.Server{}, fmt.Errorf("memory must be between 1024 MB and 65536 MB")
	}
	if req.Port < 1024 || req.Port > 65535 {
		return store.Server{}, fmt.Errorf("port must be between 1024 and 65535")
	}
	if !req.EULAAccepted {
		return store.Server{}, fmt.Errorf("you must accept the Minecraft EULA before creating a server")
	}
	if !portAvailable(req.Port) {
		return store.Server{}, fmt.Errorf("port %d is already in use", req.Port)
	}
	if m.store.PortInUse(req.Port) {
		return store.Server{}, fmt.Errorf("port %d is already assigned to another UNNAMED PTERO server", req.Port)
	}
	javaMajor, err := m.installer.RequiredJava(ctx, version)
	if err != nil {
		return store.Server{}, fmt.Errorf("could not determine the required Java version: %w", err)
	}
	parent, err := system.ValidateServerPath(req.ParentDirectory)
	if err != nil {
		return store.Server{}, err
	}
	folder := filepath.Join(parent, slugify(name))
	if _, err := os.Stat(folder); err == nil {
		return store.Server{}, fmt.Errorf("folder already exists: %s", folder)
	}
	if err := os.Mkdir(folder, 0o755); err != nil {
		return store.Server{}, fmt.Errorf("create server directory: %w", err)
	}
	cleanup := true
	defer func() {
		if cleanup {
			_ = os.RemoveAll(folder)
		}
	}()
	jarPath := filepath.Join(folder, "server.jar")
	jar, err := m.installer.DownloadJar(ctx, software, version, jarPath)
	if err != nil {
		return store.Server{}, err
	}
	if err := os.WriteFile(filepath.Join(folder, "eula.txt"), []byte("# Accepted in UNNAMED PTERO server creation\neula=true\n"), 0o644); err != nil {
		return store.Server{}, err
	}
	properties := fmt.Sprintf("# Generated by UNNAMED PTERO\nserver-port=%d\nserver-ip=\nonline-mode=true\nmotd=%s\nmax-players=20\nview-distance=10\nsimulation-distance=10\nwhite-list=false\nenforce-whitelist=false\n", req.Port, strings.ReplaceAll(name, "=", "-"))
	if err := os.WriteFile(filepath.Join(folder, "server.properties"), []byte(properties), 0o644); err != nil {
		return store.Server{}, err
	}
	if err := os.MkdirAll(filepath.Join(folder, "logs"), 0o755); err != nil {
		return store.Server{}, err
	}
	id := newID()
	v := store.Server{ID: id, Name: name, Software: software, Version: version, Directory: folder, JarFile: jar, MemoryMB: req.MemoryMB, JavaMajor: javaMajor, Port: req.Port, CreatedAt: time.Now().UTC().Format(time.RFC3339)}
	if err := m.store.CreateServer(v); err != nil {
		return store.Server{}, fmt.Errorf("save server metadata: %w", err)
	}
	cleanup = false
	m.appendActivity(v, "Server instance created")
	return v, nil
}

func (m *Manager) List() ([]ServerView, error) {
	servers, err := m.store.ListServers()
	if err != nil {
		return nil, err
	}
	out := make([]ServerView, 0, len(servers))
	for _, s := range servers {
		out = append(out, ServerView{Server: s, Status: m.Status(s.ID)})
	}
	return out, nil
}

func (m *Manager) Status(id string) string {
	m.mu.RLock()
	p := m.running[id]
	starting := m.starting[id]
	m.mu.RUnlock()
	if p == nil {
		if starting {
			return "starting"
		}
		return "offline"
	}
	p.mu.Lock()
	defer p.mu.Unlock()
	return p.status
}

func (m *Manager) Start(ctx context.Context, id string) error {
	s, err := m.store.GetServer(id)
	if err != nil {
		return fmt.Errorf("server not found")
	}
	m.mu.Lock()
	if m.closing {
		m.mu.Unlock()
		return fmt.Errorf("UNNAMED PTERO is shutting down")
	}
	if m.starting[id] || m.running[id] != nil {
		m.mu.Unlock()
		return fmt.Errorf("server is already starting or running")
	}
	m.activeOps.Add(1)
	m.starting[id] = true
	m.mu.Unlock()
	opCtx, cancel := context.WithCancel(ctx)
	stopRoot := context.AfterFunc(m.rootCtx, cancel)
	defer func() {
		stopRoot()
		cancel()
		m.mu.Lock()
		delete(m.starting, id)
		m.mu.Unlock()
		m.activeOps.Done()
	}()
	ctx = opCtx
	javaMajor := s.JavaMajor
	if javaMajor <= 0 {
		javaMajor = 21
	}
	java, err := system.EnsureJava(ctx, javaMajor)
	if err != nil {
		return err
	}
	if s.JarFile == "" {
		return fmt.Errorf("server jar is missing")
	}
	logPath := filepath.Join(s.Directory, "logs", "localptero.log")
	logFile, err := os.OpenFile(logPath, os.O_CREATE|os.O_APPEND|os.O_WRONLY, 0o644)
	if err != nil {
		return err
	}
	args := []string{fmt.Sprintf("-Xms%dm", min(512, s.MemoryMB)), fmt.Sprintf("-Xmx%dm", s.MemoryMB)}
	args = append(args, parseJavaArgs(s.JavaArgs)...)
	args = append(args, "-jar", s.JarFile, "nogui")
	cmd := exec.Command(java, args...)
	cmd.Dir = s.Directory
	stdin, err := cmd.StdinPipe()
	if err != nil {
		logFile.Close()
		return err
	}
	stdout, err := cmd.StdoutPipe()
	if err != nil {
		logFile.Close()
		return err
	}
	stderr, err := cmd.StderrPipe()
	if err != nil {
		logFile.Close()
		return err
	}
	if err := configureProcess(cmd); err != nil {
		logFile.Close()
		return err
	}
	if err := cmd.Start(); err != nil {
		logFile.Close()
		return fmt.Errorf("start Java server: %w", err)
	}
	p := &runningServer{cmd: cmd, stdin: stdin, done: make(chan struct{}), status: "running"}
	m.mu.Lock()
	m.running[id] = p
	m.mu.Unlock()
	var logMu sync.Mutex
	var readers sync.WaitGroup
	consume := func(r io.Reader) {
		defer readers.Done()
		sc := bufio.NewScanner(r)
		sc.Buffer(make([]byte, 64*1024), 2*1024*1024)
		for sc.Scan() {
			line := time.Now().Format("15:04:05") + " " + sc.Text()
			logMu.Lock()
			_, _ = fmt.Fprintln(logFile, line)
			logMu.Unlock()
		}
	}
	readers.Add(2)
	go consume(stdout)
	go consume(stderr)
	go func() {
		_ = cmd.Wait()
		readers.Wait()
		_ = stdin.Close()
		_ = logFile.Close()
		p.mu.Lock()
		p.status = "offline"
		p.mu.Unlock()
		if srv, err := m.store.GetServer(id); err == nil {
			m.appendActivity(srv, "Server process exited")
		}
		close(p.done)
		m.mu.Lock()
		if m.running[id] == p {
			delete(m.running, id)
		}
		m.mu.Unlock()
	}()
	m.appendActivity(s, "Server process started")
	return nil
}

func (m *Manager) Stop(id string) error {
	m.mu.RLock()
	p := m.running[id]
	m.mu.RUnlock()
	if p == nil {
		return fmt.Errorf("server is not running")
	}
	p.mu.Lock()
	p.status = "stopping"
	_, _ = io.WriteString(p.stdin, "stop\n")
	p.mu.Unlock()
	select {
	case <-p.done:
		if srv, err := m.store.GetServer(id); err == nil {
			m.appendActivity(srv, "Server stopped")
		}
		return nil
	case <-time.After(20 * time.Second):
		_ = p.cmd.Process.Kill()
		<-p.done
		if srv, err := m.store.GetServer(id); err == nil {
			m.appendActivity(srv, "Server was force-stopped after timeout")
		}
		return nil
	}
}

func (m *Manager) Command(id, command string) error {
	if strings.ContainsAny(command, "\r\n") || len(command) > 500 {
		return fmt.Errorf("command must be a single line of at most 500 characters")
	}
	m.mu.RLock()
	p := m.running[id]
	m.mu.RUnlock()
	if p == nil {
		return fmt.Errorf("server is not running")
	}
	p.mu.Lock()
	defer p.mu.Unlock()
	if p.status != "running" {
		return fmt.Errorf("server is stopping")
	}
	_, err := fmt.Fprintln(p.stdin, command)
	return err
}

func (m *Manager) Shutdown() {
	m.mu.Lock()
	if !m.closing {
		m.closing = true
		m.rootCancel()
	}
	m.mu.Unlock()
	m.activeOps.Wait()
	m.StopAll()
}

func (m *Manager) StopAll() {
	m.mu.RLock()
	ids := make([]string, 0, len(m.running))
	for id := range m.running {
		ids = append(ids, id)
	}
	m.mu.RUnlock()
	var wg sync.WaitGroup
	for _, id := range ids {
		wg.Add(1)
		go func(serverID string) { defer wg.Done(); _ = m.Stop(serverID) }(id)
	}
	wg.Wait()
}

// ClearConsole removes only the output mirror shown in the UNNAMED PTERO console.
// Minecraft's own logs/latest.log and all world/server files are left untouched.
// The server must be fully offline so no process reader can append while it is cleared.
func (m *Manager) ClearConsole(id string) error {
	if status := m.Status(id); status != "offline" {
		return fmt.Errorf("wait for the server to stop before clearing console output (current status: %s)", status)
	}
	s, err := m.store.GetServer(id)
	if err != nil {
		return fmt.Errorf("server not found")
	}
	logPath := filepath.Join(s.Directory, "logs", "localptero.log")
	if err := os.MkdirAll(filepath.Dir(logPath), 0o755); err != nil {
		return fmt.Errorf("prepare console log: %w", err)
	}
	f, err := os.OpenFile(logPath, os.O_CREATE|os.O_WRONLY|os.O_TRUNC, 0o644)
	if err != nil {
		return fmt.Errorf("clear console output: %w", err)
	}
	if err := f.Close(); err != nil {
		return fmt.Errorf("finish clearing console output: %w", err)
	}
	m.appendActivity(s, "Console output cleared manually")
	return nil
}

func (m *Manager) Logs(id string, limit int) ([]string, error) {
	s, err := m.store.GetServer(id)
	if err != nil {
		return nil, fmt.Errorf("server not found")
	}
	if limit < 1 || limit > 1000 {
		limit = 300
	}
	f, err := os.Open(filepath.Join(s.Directory, "logs", "localptero.log"))
	if err != nil {
		if os.IsNotExist(err) {
			return []string{}, nil
		}
		return nil, err
	}
	defer f.Close()
	lines := make([]string, 0, limit)
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 64*1024), 2*1024*1024)
	for sc.Scan() {
		lines = append(lines, sc.Text())
		if len(lines) > limit {
			lines = lines[1:]
		}
	}
	return lines, sc.Err()
}

func (m *Manager) Delete(id string, deleteFiles bool) error {
	status := m.Status(id)
	if status != "offline" {
		return fmt.Errorf("wait for the server to stop before deleting it (current status: %s)", status)
	}
	s, err := m.store.GetServer(id)
	if err != nil {
		return fmt.Errorf("server not found")
	}
	if deleteFiles {
		if err := os.RemoveAll(s.Directory); err != nil {
			return err
		}
	}
	return m.store.DeleteServer(id)
}

type StartupSettings struct {
	MemoryMB int    `json:"memoryMb"`
	JavaArgs string `json:"javaArgs"`
}

type ServerSettings struct {
	Name string `json:"name"`
	Port int    `json:"port"`
}

func (m *Manager) UpdateStartup(id string, req StartupSettings) (store.Server, error) {
	if m.Status(id) != "offline" {
		return store.Server{}, fmt.Errorf("stop the server before changing startup settings")
	}
	if req.MemoryMB < 1024 || req.MemoryMB > 65536 {
		return store.Server{}, fmt.Errorf("memory must be between 1024 MB and 65536 MB")
	}
	if len(req.JavaArgs) > 2000 || strings.ContainsAny(req.JavaArgs, "\r\n") {
		return store.Server{}, fmt.Errorf("Java arguments must be a single line of at most 2000 characters")
	}
	for _, arg := range strings.Fields(req.JavaArgs) {
		low := strings.ToLower(arg)
		if strings.HasPrefix(low, "-xms") || strings.HasPrefix(low, "-xmx") || low == "-jar" || low == "-cp" || low == "-classpath" || strings.HasPrefix(arg, "@") {
			return store.Server{}, fmt.Errorf("memory, classpath and JAR arguments are controlled by UNNAMED PTERO; remove %q", arg)
		}
	}
	s, err := m.store.GetServer(id)
	if err != nil {
		return store.Server{}, err
	}
	s.MemoryMB = req.MemoryMB
	s.JavaArgs = strings.TrimSpace(req.JavaArgs)
	if err := m.store.UpdateServer(s); err != nil {
		return store.Server{}, err
	}
	m.appendActivity(s, "Startup configuration updated")
	return s, nil
}

func (m *Manager) UpdateSettings(id string, req ServerSettings) (store.Server, error) {
	if m.Status(id) != "offline" {
		return store.Server{}, fmt.Errorf("stop the server before changing server settings")
	}
	name := strings.TrimSpace(req.Name)
	if !safeName.MatchString(name) {
		return store.Server{}, fmt.Errorf("server name must be 2–40 characters and contain only letters, numbers, spaces, dots, underscores or hyphens")
	}
	if req.Port < 1024 || req.Port > 65535 {
		return store.Server{}, fmt.Errorf("port must be between 1024 and 65535")
	}
	s, err := m.store.GetServer(id)
	if err != nil {
		return store.Server{}, err
	}
	if req.Port != s.Port && (!portAvailable(req.Port) || m.store.PortInUse(req.Port)) {
		return store.Server{}, fmt.Errorf("port %d is not available", req.Port)
	}
	oldName, oldPort := s.Name, s.Port
	s.Name, s.Port = name, req.Port
	if err := updateServerProperties(s.Directory, oldPort, req.Port, name); err != nil {
		return store.Server{}, err
	}
	if err := m.store.UpdateServer(s); err != nil {
		_ = updateServerProperties(s.Directory, req.Port, oldPort, oldName)
		return store.Server{}, err
	}
	m.appendActivity(s, "Server settings updated")
	return s, nil
}

func updateServerProperties(dir string, oldPort, newPort int, name string) error {
	path := filepath.Join(dir, "server.properties")
	b, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	scanner := bufio.NewScanner(strings.NewReader(string(b)))
	lines := []string{}
	portFound, motdFound := false, false
	for scanner.Scan() {
		line := scanner.Text()
		if strings.HasPrefix(line, "server-port=") {
			line = fmt.Sprintf("server-port=%d", newPort)
			portFound = true
		}
		if strings.HasPrefix(line, "motd=") {
			line = "motd=" + strings.ReplaceAll(strings.ReplaceAll(name, "=", "-"), "\\n", " ")
			motdFound = true
		}
		lines = append(lines, line)
	}
	if err := scanner.Err(); err != nil {
		return err
	}
	if !portFound {
		lines = append(lines, fmt.Sprintf("server-port=%d", newPort))
	}
	if !motdFound {
		lines = append(lines, "motd="+strings.ReplaceAll(name, "=", "-"))
	}
	return os.WriteFile(path, []byte(strings.Join(lines, "\n")+"\n"), 0o644)
}

func parseJavaArgs(v string) []string {
	// A deliberately simple whitespace-separated argument list; arguments are passed directly to java.exe, never through a shell.
	return strings.Fields(v)
}

func (m *Manager) appendActivity(s store.Server, message string) {
	_ = os.MkdirAll(filepath.Join(s.Directory, "logs"), 0o755)
	f, err := os.OpenFile(filepath.Join(s.Directory, "logs", "activity.log"), os.O_CREATE|os.O_APPEND|os.O_WRONLY, 0o644)
	if err != nil {
		return
	}
	defer f.Close()
	_, _ = fmt.Fprintf(f, "%s  %s\n", time.Now().Format(time.RFC3339), message)
}

